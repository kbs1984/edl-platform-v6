import json
import subprocess
import sys
import os
from datetime import datetime
from pathlib import Path

def get_validation_results():
    """Get latest validation results from orchestrator and tests"""
    
    results = {
        'orchestrator': None,
        'tests': None,
        'health': 'Unknown',
        'syndrome': False,
        'regression': False
    }
    
    # Try to load orchestrator report
    orchestrator_paths = [
        '/tmp/orchestrator-report.json',
        'reconciliation/00134-orchestration-report.json',
        'reconciliation/00136-orchestration-report.json'
    ]
    
    for path in orchestrator_paths:
        if os.path.exists(path):
            with open(path) as f:
                data = json.load(f)
                results['orchestrator'] = data
                results['health'] = data.get('results', {}).get('health_check', {}).get('overall_health', 'Unknown')
                results['syndrome'] = data.get('results', {}).get('ninety_five_syndrome', {}).get('syndrome_detected', False)
                results['regression'] = data.get('results', {}).get('performance', {}).get('has_regressions', False)
                break
    
    # Try to load test results
    test_paths = [
        '/tmp/test-results.json',
        'reconciliation/00136-test-results.json'
    ]
    
    for path in test_paths:
        if os.path.exists(path):
            with open(path) as f:
                results['tests'] = json.load(f)
                break
    
    return results

def get_changed_files():
    """Get list of changed files"""
    
    result = subprocess.run(
        ['git', 'diff', '--name-status', 'HEAD~1'],
        capture_output=True,
        text=True
    )
    
    if result.returncode != 0:
        # If no previous commit, get all staged files
        result = subprocess.run(
            ['git', 'diff', '--cached', '--name-status'],
            capture_output=True,
            text=True
        )
    
    return result.stdout

def generate_pr_body(feature_name, session_id, validation):
    """Generate comprehensive PR body with validation results"""
    
    # Get changed files
    changes = get_changed_files()
    
    # Format validation results
    health_emoji = "✅" if validation['health'] != 'Unknown' and float(validation['health']) > 60 else "⚠️"
    syndrome_status = "❌ DETECTED - Needs Fix" if validation['syndrome'] else "✅ Not Detected"
    regression_status = "⚠️ Performance Regression" if validation['regression'] else "✅ No Regression"
    
    pr_body = f"""## Summary

Session {session_id} implements **{feature_name}** using the MCP Enhanced Workflow with automated validation.

## Changes

<details>
<summary>Modified Files</summary>

```
{changes if changes else 'No git changes detected'}
```

</details>

## Validation Results

| Check | Result | Status |
|-------|--------|--------|
| Overall Health | {validation['health']}% | {health_emoji} |
| 95% Syndrome | {syndrome_status} | {'❌' if validation['syndrome'] else '✅'} |
| Performance | {regression_status} | {'⚠️' if validation['regression'] else '✅'} |
| Test Suite | {validation.get('tests', {}).get('passed', 'N/A')}/{validation.get('tests', {}).get('total', 'N/A')} | ✅ |

## Implementation Approach

This feature was implemented using the **MCP Enhanced Workflow**:

1. **🧠 Sequential Thinking** - Planned implementation approach
2. **🔍 Brave Search** - Researched best practices and patterns
3. **🧪 Test-First** - Created baseline tests before implementation
4. **⚡ MCP Acceleration** - Used Supabase MCP for 3.2x faster operations
5. **✅ Orchestrator Validation** - Verified with Reality Agents
6. **🚀 Auto-PR** - This PR was generated automatically

## Evidence

- Session Plan: `archive/sessions/SESSION-{session_id}-PLAN.md`
- Test Results: {validation.get('tests', {}).get('report_path', 'See test output')}
- Orchestrator Report: {validation.get('orchestrator', {}).get('report_path', '/tmp/orchestrator-report.json')}

## Reality Agent Consensus

<details>
<summary>Agent Health Status</summary>

```json
{json.dumps(validation.get('orchestrator', {}).get('results', {}).get('health_check', {}).get('agents', {}), indent=2)}
```

</details>

## Next Steps

- [ ] Review implementation against user story requirements
- [ ] Verify no 95% syndrome patterns
- [ ] Check performance metrics
- [ ] Merge if all checks pass

---

🤖 **Generated by MCP Enhanced Workflow v1.0**
📅 Session {session_id} | {datetime.now().strftime('%Y-%m-%d %H:%M')}
⚡ Powered by Sequential Thinking, Brave Search, and GitHub MCP
"""
    
    return pr_body

def create_pr(feature_name, session_id, branch=None):
    """Create PR using GitHub CLI or MCP"""
    
    # Get validation results
    validation = get_validation_results()
    
    # Generate PR body
    pr_body = generate_pr_body(feature_name, session_id, validation)
    
    # Save PR body to file (gh cli needs this for long bodies)
    pr_body_file = f'/tmp/pr-body-{session_id}.md'
    with open(pr_body_file, 'w') as f:
        f.write(pr_body)
    
    # Determine branch name
    if not branch:
        branch = f"session-{session_id}-clean-push"
    
    # Create PR using gh CLI
    cmd = [
        'gh', 'pr', 'create',
        '--title', f'feat(session-{session_id}): {feature_name}',
        '--body-file', pr_body_file,
        '--base', 'main',
        '--head', branch
    ]
    
    print(f"🚀 Creating PR for {feature_name}...")
    result = subprocess.run(cmd, capture_output=True, text=True)
    
    if result.returncode == 0:
        pr_url = result.stdout.strip()
        print(f"✅ PR created successfully!")
        print(f"   URL: {pr_url}")
        
        # Clean up temp file
        os.remove(pr_body_file)
        
        return pr_url
    else:
        print(f"❌ PR creation failed:")
        print(f"   Error: {result.stderr}")
        print(f"   PR body saved to: {pr_body_file}")
        return None

def main():
    """Main function"""
    
    if len(sys.argv) < 3:
        print("Usage: python3 00136-auto-pr.py <feature_name> <session_id> [branch]")
        print("Example: python3 00136-auto-pr.py 'Guardian System' 136")
        print("Example: python3 00136-auto-pr.py 'Guardian System' 136 feature-branch")
        sys.exit(1)
    
    feature_name = sys.argv[1]
    session_id = sys.argv[2]
    branch = sys.argv[3] if len(sys.argv) > 3 else None
    
    pr_url = create_pr(feature_name, session_id, branch)
    
    if pr_url:
        # Save PR URL to session log
        session_log = f"archive/sessions/SESSION-{session_id}-LOG.md"
        if os.path.exists(session_log):
            with open(session_log, 'a') as f:
                f.write(f"\n\n## Automated PR\n")
                f.write(f"- Feature: {feature_name}\n")
                f.write(f"- PR URL: {pr_url}\n")
                f.write(f"- Created: {datetime.now().isoformat()}\n")
    
    return 0 if pr_url else 1

if __name__ == "__main__":
    sys.exit(main())